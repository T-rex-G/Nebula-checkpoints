'use strict';

const assert = require('assert');
const { loadsInShell } = require('./helpers/web-shell');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'apps', 'web', 'index.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'apps', 'web', 'src', 'legacy', 'app.js'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'apps', 'web', 'src', 'offline', 'sw.js'), 'utf8');

for (const id of [
  'trustSummary', 'trustConnection', 'trustPipeline',
  'trustRisk', 'trustAction', 'trustEvidence', 'a11yStatus'
]) assert(html.includes(`id="${id}"`), `missing #${id}`);
/*
 * What the trust summary and the error dialog say -- every evidence state,
 * each part of a failure, a credential redacted, a standing named for its
 * weakest field -- is asked of the module (test/trust-ui.test.js); that the
 * dialog is a modal dialog that says every part, copies its correlation ID and
 * shows a provider's markup as text is the browser's
 * (test/e2e/public-alpha-states.spec.js).
 */
assert(app.includes('Promise.allSettled(['));
for (const endpoint of ['live-events/status', 'access-surface', 'evidence']) {
  assert(app.includes(endpoint), `trust summary must load ${endpoint}`);
}
/*
 * That the workbench draws its trust summary with this module, and answers a
 * refused or failed action with its error dialog -- safe state and next action
 * included -- is the browser's: test/e2e/public-alpha-states.spec.js opens a
 * repository in each state and drives each failure, as the server answers it.
 */
assert(loadsInShell('apps/web/src/features/trust/TrustViews.tsx'), 'the trust interface is part of the page');
assert(!/trust-ui/.test(sw), 'the shell list is generated by the build, not kept by hand');

console.log('trust UI contract tests passed');
